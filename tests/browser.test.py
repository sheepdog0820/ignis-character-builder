import os,sys,json
from pathlib import Path

from playwright.sync_api import sync_playwright
root=Path(__file__).resolve().parents[1];out=root/'qa-output';out.mkdir(exist_ok=True)
checks=[]
def check(name,condition=True):
 assert condition,name
 checks.append(name);print('PASS',name,flush=True)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path=os.environ.get('IGNIS_BROWSER_PATH',r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe'),headless=True)
 context=browser.new_context(viewport={'width':1440,'height':1100},accept_downloads=True)
 page=context.new_page();errors=[];requests=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.on('request',lambda r:requests.append(r.url))
 page.goto('http://127.0.0.1:8765/');page.locator('#pc-name').wait_for()
 page.screenshot(path=str(out/'desktop-step1.png'),full_page=True)
 check('初期画面が表示される')
 page.locator('#pc-name').fill('試験用の仮名');page.locator('#pc-notes').fill('<img src=x onerror=alert(1)>\n任意メモ')
 page.locator('[data-step="2"]').click();check('ステップ2へ移動',page.locator('[data-panel="2"]').is_visible())
 page.locator('[data-step="1"]').click();check('戻るとPC名・メモが保持',page.locator('#pc-name').input_value()=='試験用の仮名')
 page.locator('[data-step="2"]').click();page.locator('#main-b2').click()
 check('主技能の3個目を拒否',not page.locator('#main-b2').is_checked() and '2枠' in page.locator('#message').inner_text())
 page.locator('#main-b3').uncheck();page.locator('#main-b2').check();check('手動技能交換',page.locator('#main-b2').is_checked())
 page.locator('#weapon-0').select_option('long_blade');page.locator('[data-step="3"]').click()
 check('主武器の射程が反映','射程 0～1' in page.locator('#sheet').inner_text())
 check('自由記述をHTMLとして実行しない',page.locator('#sheet img').count()==0 and '<img src=x onerror=alert(1)>' in page.locator('.pc-memo').inner_text())
 page.locator('#save-local').click();check('端末保存成功','保存しました' in page.locator('#save-status').inner_text())
 stored=json.loads(page.evaluate("localStorage.getItem('ignis.character.v1')"));check('保存には入力選択のみ','stats' not in stored and stored['weapons'][0]=='long_blade')
 page.reload();page.locator('#pc-name').wait_for(state='attached');check('再読み込みから自動復元',page.locator('#sheet-name').inner_text()=='試験用の仮名')
 page.locator('[data-step="1"]').click();page.locator('#pc-name').fill('変更中');page.locator('#restore-local').click();check('端末保存の手動復元',page.locator('#pc-name').input_value()=='試験用の仮名')
 page.locator('[data-step="3"]').click()
 with page.expect_download() as dl:page.locator('#export').click()
 download=dl.value;download.save_as(str(out/'export.json'))
 check('JSON保存',json.loads((out/'export.json').read_text('utf-8'))==stored)
 page.locator('[data-step="1"]').click();page.locator('#pc-name').fill('置換前')
 page.locator('#import').set_input_files(str(out/'export.json'));page.wait_for_timeout(100)
 check('JSONの読込復元',page.locator('#pc-name').input_value()=='試験用の仮名')
 for label,obj in [('invalid',b'{'),('wrong-type',json.dumps({**stored,'name':{}}).encode()),('unknown-id',json.dumps({**stored,'weapons':['missing','phase']}).encode()),('unsafe-key',b'{"__proto__":{"polluted":true}}')]:
  page.locator('#import').set_input_files({'name':label+'.json','mimeType':'application/json','buffer':obj});page.wait_for_timeout(100)
  check('不正JSON拒否と入力保持 '+label,'読込エラー' in page.locator('#message').inner_text() and page.locator('#pc-name').input_value()=='試験用の仮名')
 page.locator('#import').set_input_files({'name':'huge.json','mimeType':'application/json','buffer':b' '*65537});page.wait_for_timeout(100)
 check('過大JSON拒否','64KB' in page.locator('#message').inner_text())
 page.locator('[data-step="1"]').click();page.locator('.class-grid').nth(0).get_by_role('button',name='フィールドコントローラー',exact=False).click()
 check('クラス変更は選択の入れ替えを明示','外れた選択' in page.locator('#message').inner_text())
 check('クラス変更でPC名保持',page.locator('#pc-name').input_value()=='試験用の仮名')
 page.locator('[data-step="2"]').click();page.locator('#weapon-1').select_option('control_projector')
 check('タグ不整合の日本語エラー','適合タグ' in page.locator('[data-panel="2"] .legality').inner_text())
 page.locator('#save-local').click();check('不適合構成の保存を止める','保存前に' in page.locator('#message').inner_text())
 page.locator('#weapon-1').select_option('economy_phase');check('正式互換タグでエラー解除','作成条件を確認' in page.locator('[data-panel="2"] .legality').inner_text())
 page.locator('[data-step="3"]').click();page.screenshot(path=str(out/'desktop-sheet.png'),full_page=True)
 # Hostile storage data and blocked/quota storage must not destroy edited inputs.
 page.evaluate("localStorage.setItem('ignis.character.v1','{')");page.locator('#restore-local').click()
 check('不正端末データを安全に拒否','現在の入力は保持' in page.locator('#message').inner_text())
 page.evaluate("() => {Storage.prototype.setItem=function(){throw new DOMException('quota','QuotaExceededError')}}")
 page.locator('#save-local').click();check('端末保存失敗を日本語で案内','保存に失敗' in page.locator('#message').inner_text())
 page.emulate_media(media='print');page.pdf(path=str(out/'sheet.pdf'),format='A4',print_background=True)
 page.screenshot(path=str(out/'print-view.png'),full_page=True)
 check('印刷時はシートのみ',page.locator('.steps').is_hidden() and page.locator('#sheet').is_visible() and page.locator('.toolbar').is_hidden())
 page.emulate_media(media='screen')
 check('ブラウザ実行エラーなし',not errors)
 check('入力の外部通信なし',all(u.startswith('http://127.0.0.1:8765/') for u in requests))
 mobile=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
 mp=mobile.new_page();mp.goto('http://127.0.0.1:8765/');mp.locator('#pc-name').wait_for()
 for n in [1,2,3]:
  mp.locator(f'[data-step="{n}"]').click();mp.screenshot(path=str(out/f'mobile-step{n}.png'),full_page=True)
  check(f'390pxモバイル ステップ{n}横はみ出しなし',mp.evaluate('document.documentElement.scrollWidth <= innerWidth'))
 # Additional narrow viewport and project subdirectory deployment paths.
 mp.set_viewport_size({'width':320,'height':700})
 check('320pxシート横はみ出しなし',mp.evaluate('document.documentElement.scrollWidth <= innerWidth'))
 mp.locator('[data-step="2"]').click();check('320px技能画面横はみ出しなし',mp.evaluate('document.documentElement.scrollWidth <= innerWidth'))
 browser.close()
(out/'browser-results.json').write_text(json.dumps({'passed':checks,'count':len(checks),'pageErrors':errors,'requests':sorted(set(requests))},ensure_ascii=False,indent=2),'utf-8')
print('TOTAL',len(checks))
